#!/usr/bin/env python3
"""Builds gambatte_sdl/mpgb_paletas.h: the Game Boy Color palettes for Game Boy
games, from gbcpalettes.h of gambatte-libretro (GPL-2.0, (C) 2007 Sindre Aamas):
https://github.com/libretro/gambatte-libretro/blob/master/libgambatte/libretro/gbcpalettes.h

- the 12 palettes picked with a button combo on the GBC boot screen
- the palette the GBC picked by itself for known titles (fallback: Dark Green)

Usage: gerar-paletas.py gbcpalettes.h saida/mpgb_paletas.h
"""
import re
import sys

SRC, OUT = sys.argv[1], sys.argv[2]
text = open(SRC).read()

arrays = {}
for m in re.finditer(r'static const unsigned short (\w+)\[\] = \{(.*?)\};', text, re.S):
    cols = [int(c, 16) for c in re.findall(r'0x([0-9A-Fa-f]{6})', m.group(2))]
    if len(cols) == 12:
        arrays[m.group(1)] = cols

def table(name):
    body = re.search(r'static const GbcPaletteEntry ' + name + r'\[\] = \{(.*?)\n\};', text, re.S).group(1)
    return re.findall(r'\{\s*"([^"]+)",\s*(\w+)\s*\}', body)

# GBC boot-screen palettes, in the order a player would see them in a list
NAMES = {
    'GBC - Dark Green': 'Verde escuro (GBC)', 'GBC - Green': 'Verde', 'GBC - Blue': 'Azul',
    'GBC - Dark Blue': 'Azul escuro', 'GBC - Brown': 'Marrom', 'GBC - Dark Brown': 'Marrom escuro',
    'GBC - Red': 'Vermelha', 'GBC - Orange': 'Laranja', 'GBC - Yellow': 'Amarela',
    'GBC - Pastel Mix': 'Pastel', 'GBC - Grayscale': 'Tons de cinza', 'GBC - Inverted': 'Invertida',
}
ORDER = list(NAMES)
dirpal = dict(table('gbcDirPalettes'))
titles = table('gbcTitlePalettes')

def c_array(cols):
    return '{' + ', '.join('0x%06X' % c for c in cols) + '}'

lines = [
    '/* Generated by emulador/ui/gerar-paletas.py from gbcpalettes.h of gambatte-libretro',
    ' * (GPL-2.0, Copyright (C) 2007 Sindre Aamas). Do not edit.',
    ' * 12 colours per palette: background 0-3, sprites 0 (4-7), sprites 1 (8-11), RGB. */',
    '#ifndef MPGB_PALETAS_H', '#define MPGB_PALETAS_H', '#include <stdint.h>', '',
    'struct mpgb_paleta { const char *id; const char *nome; uint32_t c[12]; };',
    'struct mpgb_paleta_titulo { const char *titulo; uint32_t c[12]; };', '',
    '/* id: value stored in the settings (PALNAME GBC:<id>) */',
    'static const mpgb_paleta mpgb_paletas_gbc[] = {',
]
for key in ORDER:
    pid = key.replace('GBC - ', '').replace(' ', '')
    lines.append('\t{ "%s", "%s", %s },' % (pid, NAMES[key], c_array(arrays[dirpal[key]])))
lines += ['};', '#define MPGB_N_PALETAS_GBC %d' % len(ORDER), '',
          '/* palette the GBC chose by itself for these titles (header title, 0x134) */',
          'static const mpgb_paleta_titulo mpgb_paletas_titulo[] = {']
for title, arr in titles:
    if arr in arrays:
        lines.append('\t{ "%s", %s },' % (title.replace('\\', '\\\\').replace('"', '\\"'), c_array(arrays[arr])))
lines += ['};', '#define MPGB_N_PALETAS_TITULO %d' % sum(1 for _, a in titles if a in arrays), '',
          '/* other titles: the GBC default (A + Right) */',
          'static const uint32_t mpgb_paleta_gbc_padrao[12] = %s;' % c_array(arrays[dirpal['GBC - Dark Green']]),
          '', '#endif']
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(len(ORDER), 'paletas,', sum(1 for _, a in titles if a in arrays), 'titulos')
