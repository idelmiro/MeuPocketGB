#!/usr/bin/env python3
"""Turns the Nunito font (SIL OFL 1.1, emulador/ui/OFL-Nunito.txt) into C tables
that are compiled into the emulator (gambatte_sdl/mpgb_fonte.h): no font file
to open or decode when the console starts.

Usage: gerar-fonte.py "emulador/ui/Nunito[wght].ttf" saida/mpgb_fonte.h
Needs Pillow with FreeType variable-font support.

Each size is one table of glyphs (8-bit coverage, cropped) for ASCII,
Latin-1 (Portuguese accents) and the ellipsis.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF, OUT = sys.argv[1], sys.argv[2]
# name, pixel size, weight
SIZES = [('item', 16, 'ExtraBold'), ('hint', 11, 'ExtraBold'), ('key', 10, 'Bold')]
CHARS = list(range(32, 127)) + list(range(160, 256)) + [0x2026]


def glyphs(size, weight):
    f = ImageFont.truetype(TTF, size)
    f.set_variation_by_name(weight)
    ascent, descent = f.getmetrics()
    out = []
    for cp in CHARS:
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        x0, y0, x1, y1 = f.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        data = b''
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
            data = im.tobytes()
        out.append((cp, x0, y0, w, h, adv, data))
    return ascent, descent, out


def main():
    lines = ['/* Generated by emulador/ui/gerar-fonte.py from Nunito (SIL OFL 1.1). Do not edit. */',
             '#ifndef MPGB_FONTE_H', '#define MPGB_FONTE_H', '#include <stdint.h>', '',
             'struct mpgb_glyph { uint16_t cp; int8_t x, y; uint8_t w, h, adv; uint32_t off; };',
             'struct mpgb_font { const mpgb_glyph *g; int n; const uint8_t *px; int ascent, descent; };', '']
    for name, size, weight in SIZES:
        ascent, descent, gl = glyphs(size, weight)
        blob, table = bytearray(), []
        for cp, x, y, w, h, adv, data in gl:
            table.append(f'{{{cp},{x},{y},{w},{h},{adv},{len(blob)}}}')
            blob += data
        lines.append(f'static const uint8_t mpgb_px_{name}[{max(1, len(blob))}] = {{')
        for i in range(0, len(blob), 32):
            lines.append(','.join(str(b) for b in blob[i:i + 32]) + ',')
        lines.append('};')
        lines.append(f'static const mpgb_glyph mpgb_g_{name}[{len(table)}] = {{')
        for i in range(0, len(table), 8):
            lines.append(','.join(table[i:i + 8]) + ',')
        lines.append('};')
        lines.append(f'static const mpgb_font mpgb_font_{name} = {{ mpgb_g_{name}, {len(table)}, mpgb_px_{name}, {ascent}, {descent} }};')
        lines.append('')
    lines.append('#endif')
    open(OUT, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
